/**
 * Locale -> dictionary. Both BCP-47 tags (what m_rgLocalesToUse reports,
 * e.g. "pt-BR") and Steam's own API language names (e.g. "brazilian") are
 * registered, because either form has been observed in the wild. pick()
 * tries the full tag first, so "zh-TW" beats the bare "zh" entry.
 */
const LANGS: Record<string, Dict> = {
  en, english: en,
  ko, koreana: ko,
  de, german: de,
  fr, french: fr,
  ru, russian: ru,
  pl, polish: pl,
  tr, turkish: tr,
  pt: ptBr, "pt-br": ptBr, brazilian: ptBr, portuguese: ptBr,
  zh: zhCn, "zh-cn": zhCn, "zh-hans": zhCn, schinese: zhCn,
  "zh-tw": zhTw, "zh-hk": zhTw, "zh-hant": zhTw, tchinese: zhTw,
};

function steamLanguage(): string {
  try {
    const lm = (window as any).LocalizationManager;
    const loc = lm?.m_rgLocalesToUse?.[0];
    if (typeof loc === "string" && loc) return loc;
  } catch {
    /* not in Steam context */
  }
  return (navigator.language || "en").toLowerCase();
}

function pick(): Dict {
  // Steam has been seen reporting both "pt-BR" and "pt_BR"; normalise so a
  // single set of hyphenated keys covers both.
  const lang = steamLanguage().toLowerCase().replace(/_/g, "-");
  if (LANGS[lang]) return LANGS[lang];
  const short = lang.split("-")[0];
  return LANGS[short] ?? en;
}

const table = pick();

/** t("watching_folders", { n: 5 }) - {placeholders} are substituted. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
